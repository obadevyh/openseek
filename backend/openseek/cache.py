"""Tile cache (SR-15, SR-16).

Layout (every component derived from validated lowercase hex IDs / integers):
  <data>/cache/<fp[0:2]>/<fp>/<PROFILE>/tiles/<k>.jpg
  <data>/cache/<fp[0:2]>/<fp>/<PROFILE>/sheets/<n>_<v>.jpg
PROFILE is the thumbnail quality preset's id (quality.py; Standard = t320x180q75g10v1, the original
layout). Each (fingerprint, quality) has its own tile set: tiles of one quality are never served or
counted as another, and changing the quality never deletes the others (eviction still removes a whole
fingerprint, every quality at once). A tile is only published when its JPEG really has the preset's
dimensions. Tiles are written individually and atomically (temp + fsync + rename) and are immutable once
published. Every read validates the JPEG (SOI/EOI markers + recorded size); a corrupt tile is
deleted, unpublished and regenerated by the scheduler. Sheets (the preset's grid; Standard 10x10 tiles,
3200x1800) are composed on demand from tiles and cached per fill version. Eviction: least recently used
fingerprint first when the total exceeds the byte cap, plus age-based retention.
"""
from __future__ import annotations

import io
import logging
import os
import secrets
import shutil
import threading
import time
from dataclasses import dataclass, field
from pathlib import Path
from typing import Callable

from .db import DB
from .ids import is_fingerprint
from .quality import BY_PROFILE, DEFAULT, STANDARD, Quality

log = logging.getLogger("openseek.cache")

# the Standard preset (kept for importers that predate quality presets)
PROFILE = STANDARD.profile     # tile geometry/quality/grid/extractor version (part of the path)
TILE_W, TILE_H = STANDARD.w, STANDARD.h
SHEET_COLS, SHEET_ROWS = STANDARD.cols, STANDARD.rows
PER_SHEET = STANDARD.per_sheet
MIN_JPEG = 125
POSIX = os.name == "posix"


def jpeg_ok(data: bytes | None) -> bool:
    return bool(data) and len(data) >= MIN_JPEG and data[:3] == b"\xff\xd8\xff" and data[-2:] == b"\xff\xd9"


def jpeg_size(data: bytes) -> tuple[int, int] | None:
    """(width, height) from the first SOF marker, without decoding. None when there is none."""
    i, n = 2, len(data)
    while i + 4 <= n:
        if data[i] != 0xFF:
            return None
        m = data[i + 1]
        if m == 0xFF:
            i += 1
            continue
        if m == 0x01 or 0xD0 <= m <= 0xD8:
            i += 2
            continue
        seg = int.from_bytes(data[i + 2:i + 4], "big")
        if 0xC0 <= m <= 0xCF and m not in (0xC4, 0xC8, 0xCC):
            if i + 9 > n:
                return None
            return int.from_bytes(data[i + 7:i + 9], "big"), int.from_bytes(data[i + 5:i + 7], "big")
        if m == 0xDA or seg < 2:
            return None
        i += 2 + seg
    return None


def secure_mkdir(path: Path) -> None:
    path.mkdir(parents=True, exist_ok=True)
    if POSIX:
        os.chmod(path, 0o700)


def atomic_write(path: Path, data: bytes) -> None:
    tmp = path.with_name(f".{path.name}.{secrets.token_hex(6)}.tmp")
    flags = os.O_WRONLY | os.O_CREAT | os.O_EXCL | getattr(os, "O_BINARY", 0)
    fd = os.open(tmp, flags, 0o600)
    try:
        with os.fdopen(fd, "wb") as f:
            f.write(data)
            f.flush()
            os.fsync(f.fileno())
        os.replace(tmp, path)
    except BaseException:
        try:
            os.unlink(tmp)
        except OSError:
            pass
        raise
    if POSIX:
        try:
            dfd = os.open(path.parent, os.O_RDONLY)
            try:
                os.fsync(dfd)
            finally:
                os.close(dfd)
        except OSError:
            pass


@dataclass
class Media:
    """Per-fingerprint state every quality shares: media facts, ONE monotonic version (a client re-reads the VTT
    whenever it grows, whichever quality changed), last use and the lock."""
    fp: str
    duration_ms: int | None = None
    n_tiles: int | None = None
    version: int = 0
    last_used: float = 0.0
    lock: threading.RLock = field(default_factory=threading.RLock)
    _flushed_use: float = 0.0


class Entry:
    """The tiles of one fingerprint at one quality. The shared fields are views of the fingerprint's `Media`."""

    def __init__(self, media: Media, quality: Quality):
        self.media = media
        self.quality = quality
        self.bytes = 0                                            # this quality's tiles + sheets
        self.tiles: dict[int, int] = {}                           # k -> pts_ms
        self.sizes: dict[int, int] = {}                           # k -> file size
        self.sheet_files: dict[int, tuple[int, int]] = {}         # n -> (v, size)

    @property
    def fp(self) -> str:
        return self.media.fp

    @property
    def lock(self) -> threading.RLock:
        return self.media.lock

    @property
    def duration_ms(self) -> int | None:
        return self.media.duration_ms

    @duration_ms.setter
    def duration_ms(self, v: int | None) -> None:
        self.media.duration_ms = v

    @property
    def n_tiles(self) -> int | None:
        return self.media.n_tiles

    @n_tiles.setter
    def n_tiles(self, v: int | None) -> None:
        self.media.n_tiles = v

    @property
    def version(self) -> int:
        return self.media.version

    @version.setter
    def version(self, v: int) -> None:
        self.media.version = v

    @property
    def last_used(self) -> float:
        return self.media.last_used

    @last_used.setter
    def last_used(self, v: float) -> None:
        self.media.last_used = v


class Cache:
    def __init__(self, data_dir: Path, db: DB, max_bytes: int, retention_days: float,
                 clock: Callable[[], float] = time.time, quality: Quality = DEFAULT):
        self.root = Path(data_dir) / "cache"
        secure_mkdir(self.root)
        self.db = db
        self.max_bytes = max_bytes
        self.retention_s = retention_days * 86400.0
        self.clock = clock
        self.quality = quality                                  # the active preset: what `quality=None` means below
        self._media: dict[str, Media] = {}
        self._entries: dict[tuple[str, str], Entry] = {}        # (fp, profile) -> Entry
        self._lock = threading.RLock()
        self.on_tile_lost: Callable[[str, int], None] | None = None
        self._cleanup_tmp()

    def _q(self, quality: Quality | None) -> Quality:
        return self.quality if quality is None else quality

    # ---------------------------------------------------------------- paths
    def _dir(self, fp: str, quality: Quality | None = None) -> Path:
        if not is_fingerprint(fp):
            raise ValueError("invalid fingerprint")
        return self.root / fp[:2] / fp / self._q(quality).profile

    def _tile_path(self, fp: str, k: int, quality: Quality | None = None) -> Path:
        if not isinstance(k, int) or k < 0 or k > 10_000_000:
            raise ValueError("invalid tile index")
        return self._dir(fp, quality) / "tiles" / f"{k}.jpg"

    def _sheet_path(self, fp: str, n: int, v: int, quality: Quality | None = None) -> Path:
        if not isinstance(n, int) or n < 0 or not isinstance(v, int) or v < 0:
            raise ValueError("invalid sheet")
        return self._dir(fp, quality) / "sheets" / f"{n}_{v}.jpg"

    def _cleanup_tmp(self) -> None:
        for p in self.root.glob("*/*/*/*/.*.tmp"):
            try:
                p.unlink()
            except OSError:
                pass

    # ---------------------------------------------------------------- entries
    def _fp_bytes(self, fp: str) -> int:
        """A fingerprint's bytes across qualities: every quality's tiles (database) plus the sheets composed now."""
        r = self.db.q("SELECT COALESCE(SUM(size),0) FROM tiles WHERE fp=?", (fp,))
        sheets = sum(sz for (f, _p), e in self._entries.items() if f == fp for _v, sz in e.sheet_files.values())
        return int(r[0][0]) + sheets

    def entry(self, fp: str, quality: Quality | None = None) -> Entry | None:
        if not is_fingerprint(fp):
            return None
        q = self._q(quality)
        with self._lock:
            e = self._entries.get((fp, q.profile))
            if e is not None:
                return e
            m = self._media.get(fp)
            if m is None:
                rows = self.db.q("SELECT duration_ms, n_tiles, version, last_used FROM entries WHERE fp=?", (fp,))
                if not rows:
                    return None
                d, n, v, lu = rows[0]
                m = Media(fp, d, n, v, lu, _flushed_use=lu)
                self._media[fp] = m
            e = Entry(m, q)
            for k, pts, size in self.db.q("SELECT k, pts_ms, size FROM tiles WHERE fp=? AND profile=?",
                                          (fp, q.profile)):
                e.tiles[k] = pts
                e.sizes[k] = size
            # sheets are derived data: drop leftovers from a previous run and recount bytes
            shutil.rmtree(self._dir(fp, q) / "sheets", ignore_errors=True)
            e.bytes = sum(e.sizes.values())
            self._entries[(fp, q.profile)] = e
            self.db.x("UPDATE entries SET bytes=? WHERE fp=?", (self._fp_bytes(fp), fp))
            return e

    def ensure(self, fp: str, quality: Quality | None = None) -> Entry:
        if not is_fingerprint(fp):
            raise ValueError("invalid fingerprint")
        with self._lock:
            e = self.entry(fp, quality)
            if e is None:
                now = self.clock()
                self.db.x("INSERT OR IGNORE INTO entries(fp, version, bytes, created, last_used) VALUES(?,?,?,?,?)",
                          (fp, 0, 0, now, now))
                e = self.entry(fp, quality)
            assert e is not None
            return e

    def cached_qualities(self, fp: str) -> list[Quality]:
        """The presets holding at least one tile of this fingerprint (unknown profiles are ignored)."""
        if not is_fingerprint(fp):
            return []
        rows = self.db.q("SELECT DISTINCT profile FROM tiles WHERE fp=?", (fp,))
        return [BY_PROFILE[r[0]] for r in rows if r[0] in BY_PROFILE]

    def bump_versions(self) -> None:
        """Every fingerprint's version + 1: the active quality changed, so what a VTT lists changes too."""
        with self._lock:
            self.db.x("UPDATE entries SET version=version+1")
            for m in self._media.values():
                with m.lock:
                    m.version += 1

    def set_media(self, fp: str, duration_ms: int, n_tiles: int) -> None:
        e = self.ensure(fp)
        with e.lock:
            e.duration_ms, e.n_tiles = duration_ms, n_tiles
            self.db.x("UPDATE entries SET duration_ms=?, n_tiles=? WHERE fp=?", (duration_ms, n_tiles, fp))

    def touch(self, fp: str) -> None:
        e = self.entry(fp)
        if e is None:
            return
        m = e.media
        now = self.clock()
        m.last_used = now
        if now - m._flushed_use > 60:
            m._flushed_use = now
            self.db.x("UPDATE entries SET last_used=? WHERE fp=?", (now, fp))

    # ---------------------------------------------------------------- tiles
    def put_tile(self, fp: str, k: int, pts_ms: int, data: bytes, quality: Quality | None = None) -> int:
        """Publish tile k at `quality` (default: the active one); immutable. Returns the fingerprint's new version.
        ValueError unless `data` is a JPEG with exactly that preset's dimensions."""
        if not jpeg_ok(data):
            raise ValueError("not a JPEG")
        q = self._q(quality)
        if jpeg_size(data) != (q.w, q.h):
            raise ValueError("tile size does not match the quality preset")
        e = self.ensure(fp, q)
        with e.lock:
            if k in e.tiles:
                return e.version
            path = self._tile_path(fp, k, q)
            secure_mkdir(path.parent)
            atomic_write(path, data)
            e.tiles[k] = int(pts_ms)
            e.sizes[k] = len(data)
            e.version += 1
            e.bytes += len(data)
            now = self.clock()
            e.last_used = now
            self.db.tx([
                ("INSERT OR REPLACE INTO tiles(fp,profile,k,pts_ms,size,created) VALUES(?,?,?,?,?,?)",
                 (fp, q.profile, k, int(pts_ms), len(data), now)),
                ("UPDATE entries SET version=?, bytes=bytes+?, last_used=? WHERE fp=?",
                 (e.version, len(data), now, fp)),
            ])
            return e.version

    def drop_tile(self, fp: str, k: int, quality: Quality | None = None) -> None:
        q = self._q(quality)
        e = self.entry(fp, q)
        if e is None:
            return
        with e.lock:
            if k not in e.tiles:
                return
            try:
                self._tile_path(fp, k, q).unlink()
            except OSError:
                pass
            e.tiles.pop(k, None)
            size = e.sizes.pop(k, 0)
            e.bytes -= size
            e.version += 1
            self.db.tx([("DELETE FROM tiles WHERE fp=? AND profile=? AND k=?", (fp, q.profile, k)),
                        ("UPDATE entries SET version=?, bytes=bytes-? WHERE fp=?", (e.version, size, fp))])
        log.warning("tile %d (%s) of %s.. was corrupt; dropped for regeneration", k, q.name, fp[:8])
        cb = self.on_tile_lost
        if cb and q == self.quality:                # only the active quality is regenerated
            cb(fp, k)

    def drop_tiles_quiet(self, fp: str, ks, quality: Quality | None = None) -> int:
        """Remove many tiles in ONE transaction without the per-tile regeneration callback (the caller marks
        them missing and wakes the runner once). Returns how many were removed."""
        q = self._q(quality)
        e = self.entry(fp, q)
        if e is None:
            return 0
        removed = []
        freed = 0
        with e.lock:
            for k in ks:
                if k not in e.tiles:
                    continue
                try:
                    self._tile_path(fp, k, q).unlink()
                except OSError:
                    pass
                e.tiles.pop(k, None)
                size = e.sizes.pop(k, 0)
                e.bytes -= size
                freed += size
                removed.append(k)
            if removed:
                e.version += 1
                self.db.tx([("DELETE FROM tiles WHERE fp=? AND profile=? AND k=?", (fp, q.profile, k))
                            for k in removed]
                           + [("UPDATE entries SET version=?, bytes=bytes-? WHERE fp=?", (e.version, freed, fp))])
        return len(removed)

    def tile_bytes(self, fp: str, k: int, quality: Quality | None = None) -> bytes | None:
        q = self._q(quality)
        e = self.entry(fp, q)
        if e is None or k not in e.tiles:
            return None
        try:
            data = self._tile_path(fp, k, q).read_bytes()
        except (OSError, ValueError):
            data = None
        if not jpeg_ok(data) or len(data) != e.sizes.get(k, -1):
            self.drop_tile(fp, k, q)
            return None
        return data

    # ---------------------------------------------------------------- sheets
    def sheet_fill(self, e: Entry, n: int) -> int:
        return sum(1 for k in e.tiles if k // e.quality.per_sheet == n)

    def sheet_bytes(self, fp: str, n: int, quality: Quality | None = None) -> tuple[bytes, int] | None:
        """Compose (or reuse) sheet n of `quality` with the tiles published now. Unfilled slots are black."""
        q = self._q(quality)
        e = self.entry(fp, q)
        if e is None or n < 0:
            return None
        per, cols = q.per_sheet, q.cols
        with e.lock:
            ks = sorted(k for k in e.tiles if k // per == n)
            if not ks:
                return None
            v = len(ks)
            path = self._sheet_path(fp, n, v, q)
            cached = e.sheet_files.get(n)
            if cached and cached[0] == v:
                try:
                    data = path.read_bytes()
                    if jpeg_ok(data) and len(data) == cached[1]:
                        return data, v
                except OSError:
                    pass
            from PIL import Image

            sheet = Image.new("RGB", q.sheet_size)
            for k in ks:
                tile = self.tile_bytes(fp, k, q)
                if tile is None:
                    continue           # corrupt tile was dropped; leave the slot black
                with Image.open(io.BytesIO(tile)) as im:
                    slot = k % per
                    sheet.paste(im.convert("RGB"), ((slot % cols) * q.w, (slot // cols) * q.h))
            ks2 = [k for k in ks if k in e.tiles]
            v = len(ks2)
            if v == 0:
                return None
            buf = io.BytesIO()
            sheet.save(buf, "JPEG", quality=q.jpeg_q)
            data = buf.getvalue()
            path = self._sheet_path(fp, n, v, q)
            secure_mkdir(path.parent)
            atomic_write(path, data)
            old = e.sheet_files.get(n)
            if old and old[0] != v:
                try:
                    self._sheet_path(fp, n, old[0], q).unlink()
                except OSError:
                    pass
            delta = len(data) - (old[1] if old else 0)
            e.bytes += delta
            e.sheet_files[n] = (v, len(data))
            self.db.x("UPDATE entries SET bytes=bytes+? WHERE fp=?", (delta, fp))
            return data, v

    # ---------------------------------------------------------------- eviction
    def total_bytes(self) -> int:
        r = self.db.q("SELECT COALESCE(SUM(bytes),0) FROM entries")
        return int(r[0][0])

    def stats(self) -> dict:
        r = self.db.q("SELECT COUNT(*), COALESCE(SUM(bytes),0) FROM entries")
        t = self.db.q("SELECT COUNT(*) FROM tiles WHERE profile=?", (self.quality.profile,))
        return {"entries": r[0][0], "bytes": r[0][1], "tiles": t[0][0], "max_bytes": self.max_bytes,
                "quality": self.quality.name}

    def _delete_entry(self, fp: str) -> None:
        with self._lock:
            for key in [key for key in self._entries if key[0] == fp]:
                self._entries.pop(key, None)
            m = self._media.pop(fp, None)
            lock = m.lock if m else threading.RLock()
            with lock:
                shutil.rmtree(self.root / fp[:2] / fp, ignore_errors=True)
                self.db.tx([("DELETE FROM tiles WHERE fp=?", (fp,)), ("DELETE FROM entries WHERE fp=?", (fp,)),
                            ("DELETE FROM previews WHERE fp=?", (fp,)), ("DELETE FROM release_meta WHERE fp=?", (fp,)),
                            ("DELETE FROM borrowed WHERE src_fp=?", (fp,)), ("DELETE FROM offsets WHERE src_fp=?", (fp,))])

    def remove_entry(self, fp: str) -> bool:
        """Owner action (admin API): delete ONE cache entry. False when it is unknown."""
        if not is_fingerprint(fp) or not self.db.q("SELECT 1 FROM entries WHERE fp=?", (fp,)):
            return False
        self._delete_entry(fp)
        return True

    def evict(self, protected: set[str] | frozenset[str] = frozenset()) -> list[str]:
        with self._lock:
            for fp, m in self._media.items():    # flush in-memory last-use times
                if m.last_used > m._flushed_use:
                    m._flushed_use = m.last_used
                    self.db.x("UPDATE entries SET last_used=? WHERE fp=?", (m.last_used, fp))
            rows = self.db.q("SELECT fp, bytes, last_used FROM entries ORDER BY last_used ASC")
            total = sum(r[1] for r in rows)
            now = self.clock()
            gone = []
            for fp, size, last in rows:
                if fp in protected or not is_fingerprint(fp):
                    continue
                if now - last > self.retention_s or total > self.max_bytes:
                    self._delete_entry(fp)
                    total -= size
                    gone.append(fp)
            if gone:
                log.info("evicted %d cache entries; total now %d bytes", len(gone), total)
            return gone
